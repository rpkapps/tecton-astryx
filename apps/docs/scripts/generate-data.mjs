/**
 * Three things must survive the rewrite verbatim, because a reader meets them
 * as they are and a renamed one would match nothing:
 *
 *   - `@astryx.…` — the library's own i18n message ids, which an override has
 *     to be keyed on exactly;
 *   - `data-astryx-…` — the attributes the theme is scoped to, which a reader
 *     sees in DevTools;
 *   - `astryx-…` — the class names and CSS layer names the components carry
 *     (`astryx-dialog`, `astryx-base`, `astryx-theme`), which are what a
 *     `defineTheme` target and a hand-written override both select on.
 */
const VERBATIM =
  /@astryx\.[A-Za-z0-9_.]+|data-astryx[a-z0-9-]*|astryx-[a-z0-9-]+/g;

/**
 * A placeholder for a string that must survive the rewrite. It is a private-use
 * code point, so it can never occur in a doc object's own prose.
 */
const KEPT = '\uE000';

/** Rewrite one string: the library's name becomes Tecton's, and nothing else. */
export function speakTecton(value) {
  const kept = [];
  const masked = String(value).replace(VERBATIM, match => {
    kept.push(match);
    return `${KEPT}${kept.length - 1}${KEPT}`;
  });
  const rewritten = masked
    .replaceAll('@astryxdesign/core', '@tecton/react')
    .replaceAll('Astryx', 'Tecton')
    .replaceAll('astryx', 'tecton');
  return rewritten.replace(
    new RegExp(`${KEPT}(\\d+)${KEPT}`, 'g'),
    (_, index) => kept[index],
  );
}

/** Apply {@link speakTecton} to every string anywhere inside a doc object. */
function rewriteDeep(value) {
  if (typeof value === 'string') return speakTecton(value);
  if (Array.isArray(value)) return value.map(rewriteDeep);
  if (value && typeof value === 'object') {
    const out = {};
    for (const [key, item] of Object.entries(value)) {
      out[key] = rewriteDeep(item);
    }
    return out;
  }
  return value;
}

/** Drop `undefined` and functions so a doc survives `JSON.stringify`. */
function plainData(value) {
  return JSON.parse(
    JSON.stringify(value, (_key, item) =>
      typeof item === 'function' ? undefined : item,
    ),
  );
}

