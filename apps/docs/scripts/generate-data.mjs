#!/usr/bin/env node
/**
 * Builds the docs site: both halves of it.
 *
 * Nothing on this site is written twice, and no list of components is kept
 * here. Five kinds of source feed it:
 *
 *   - a component doc beside each component (`Button/Button.doc.mjs`),
 *   - an example doc beside each example (`Button/examples/ButtonBasic.doc.mjs`)
 *     and the example's own source, which the site renders live,
 *   - a template doc beside each page template (`templates/**\/*.doc.mjs`),
 *   - a written guide under `guides/`,
 *   - the package's built token exports and the design JSON they were
 *     transcribed from, which is what every foundations page prints.
 *
 * From those it writes two trees, both generated and both gitignored:
 *
 *   - `content/docs/**` — the MDX fumadocs compiles into pages, and the
 *     `meta.json` files that order the sidebar. Every route the site has comes
 *     from a file here, so a component added to the package appears in the
 *     navigation, in the sidebar and in the search index without anyone
 *     touching the site.
 *   - `src/generated/**` — typed TypeScript the page components read: the
 *     registries, the foundation data, and one module per example rewritten so
 *     its imports read the way a consumer would write them. Those modules are
 *     what `<LivePreview>` imports at runtime, which is how an example on this
 *     site is the same code the reader is shown.
 *
 * The package has to be built first: the foundations pages import the token
 * modules out of `packages/react/dist/`, so a token that is renamed moves the
 * documentation with it rather than leaving a stale table behind.
 */
