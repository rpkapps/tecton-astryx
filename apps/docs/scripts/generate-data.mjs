  // `<slug>/Template.tsx` beside `<slug>/template.doc.mjs`; a template
  // authored as `<Name>.tsx` + `<Name>.doc.mjs` still resolves by stem.
  const sibling = path.join(path.dirname(file), 'Template.tsx');
