/** The body of one component page, in the order upstream's own page reads. */
function componentMdx(page) {
  const sections = [];

  // The showcase leads the page, the way upstream's own component page does —
  // but as an example block rather than a bare card, so the code that drew it is
  // one tab away. It is then not repeated in the Examples section below.
  const showcase = page.showcase ? blockById.get(page.showcase) : null;
  if (showcase) sections.push(exampleMdx(showcase));

  sections.push('## Usage');
  if (page.description) sections.push(mdxText(page.description));
  sections.push(
    fence(`import {${page.moduleName}} from '${page.importPath}';`, 'ts'),
  );

  if ((page.usage?.anatomy ?? []).length > 0) {
    sections.push('### Anatomy');
    sections.push(`<AnatomyTable ${attrs({name: page.name})} />`);
  }

  const practices = page.usage?.bestPractices ?? [];
  if (practices.length > 0) {
    sections.push('### Best practices');
    // One row per practice, as upstream's own table has — the guidance is the
    // row's badge and the prose is the row. The prose stays Markdown in the MDX
    // so the search index reads it; only the framing is a component.
    const rows = practices
      .map(
        entry =>
          `<Practice kind={${JSON.stringify(entry.guidance ? 'do' : 'dont')}}>\n\n${mdxText(
            entry.description,
          )}\n\n</Practice>`,
      )
      .join('\n\n');
    sections.push(`<BestPractices>\n\n${rows}\n\n</BestPractices>`);
  }

  if (page.isHook && (page.params?.length || page.returns?.length)) {
    sections.push('## Signature');
    sections.push(`<HookSignature ${attrs({name: page.name})} />`);
  }

  if (!page.isHook && page.props.length > 0) {
    if (page.playground) {
      sections.push('## Playground');
      sections.push(
        'Change a prop and the preview changes with it. The table is the same props table it would otherwise be.',
      );
      sections.push(`<Playground ${attrs({name: page.name})} />`);
    } else {
      sections.push('## Props');
      sections.push(`<PropsTable ${attrs({name: page.name})} />`);
    }
  }

  const examples = page.examples
    .map(id => blockById.get(id))
    .filter(example => example !== showcase);
  if (examples.length > 0) {
    sections.push('## Examples');
    sections.push('Common configurations, variations, and states.');
    for (const example of examples) sections.push(exampleMdx(example));
  }

  if (page.theming) {
    sections.push('## Theming');
    sections.push(`<Theming ${attrs({name: page.name})} />`);
  }

  if ((page.usage?.accessibility ?? []).length > 0) {
    sections.push('## Accessibility');
    sections.push(`<Accessibility ${attrs({name: page.name})} />`);
  }

  const subsWithProps = page.subcomponents.filter(
    sub => sub.props.length > 0 || sub.params?.length || sub.returns?.length,
  );
  if (subsWithProps.length > 0) {
    sections.push('## Parts');
    sections.push(
      `The components ${page.moduleName} is made of, each with the props it takes.`,
    );
    for (const sub of subsWithProps) {
      sections.push(`### ${sub.displayName}`);
      if (sub.description) sections.push(mdxText(sub.description));
      sections.push(
        `<PartTable ${attrs({component: page.name, name: sub.name})} />`,
      );
    }
  }

  if (page.keywords.length > 0) {
    sections.push('## Keywords');
    sections.push(page.keywords.map(word => `\`${word}\``).join(' · '));
  }

  const related = [
    ...(page.relatedComponents ?? []),
    ...(page.relatedHooks ?? []),
  ].filter(name => pageByName.has(name) && name !== page.name);
  if (related.length > 0) {
    sections.push('## Related');
    sections.push(`<Related ${attrs({names: related})} />`);
  }

  return `${frontmatter({
    title: page.displayName,
    description: page.description || page.summary,
  })}\n\n${MDX_BANNER}\n\n${sections.join('\n\n')}\n`;
}

