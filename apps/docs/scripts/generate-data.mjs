function buildChangelog() {
  const full = path.join(REPO_ROOT, changelogSource);
  if (!fs.existsSync(full)) return [];
  const releases = [];
  let release;
  let section;
  for (const line of fs.readFileSync(full, 'utf8').split(/\r?\n/)) {
    const heading = /^##\s+(?:\[)?([^\]\s]+)(?:\])?(?:\s+[—-]\s+(.+))?$/.exec(
      line,
    );
    if (heading) {
      release = {version: heading[1], date: heading[2] ?? '', sections: []};
      releases.push(release);
      section = undefined;
      continue;
    }
    const subheading = /^###\s+(.+)$/.exec(line);
    if (subheading && release) {
      section = {title: subheading[1].trim(), items: []};
      release.sections.push(section);
      continue;
    }
    const item = /^[-*]\s+(.+)$/.exec(line);
    if (item && release) {
      if (!section) {
        section = {title: 'Changes', items: []};
        release.sections.push(section);
      }
      section.items.push(item[1].trim());
      continue;
    }
    if (/^\s+\S/.test(line) && section && section.items.length > 0) {
      const last = section.items.length - 1;
      section.items[last] = `${section.items[last]} ${line.trim()}`;
    }
  }
  return releases;
}

