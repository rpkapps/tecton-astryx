/** Every value and type name the package's barrel exports. */
function barrelExports(entry, seen = new Set()) {
  const full = path.join(PACKAGE_SRC, entry);
  if (!fs.existsSync(full) || seen.has(full)) return new Set();
  seen.add(full);
  const source = fs.readFileSync(full, 'utf8').replace(/\r\n/g, '\n');
  const names = new Set();
  for (const match of source.matchAll(/export\s+(?:type\s+)?\{([^}]*)\}/g)) {
    for (const name of match[1].split(',')) {
      const trimmed = name
        .trim()
        .replace(/^type\s+/, '')
        .replace(/^.*\s+as\s+/, '');
      if (trimmed) names.add(trimmed);
    }
  }
  // Names declared and exported in place (`export type X = …`,
  // `export const x = …`, `export function X()`).
  for (const match of source.matchAll(
    /^export\s+(?:declare\s+)?(?:const|let|function|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/gm,
  )) {
    names.add(match[1]);
  }
  // `export * from './x.js'` re-exports another module wholesale (the barrel
  // keeps its generated pass-through components in one); follow it.
  for (const match of source.matchAll(/export\s+\*\s+from\s+'(\.[^']*)'/g)) {
    const target = path
      .join(path.dirname(entry), match[1])
      .replace(/\.js$/, '.ts');
    for (const name of barrelExports(target, seen)) names.add(name);
    const tsx = target.replace(/\.ts$/, '.tsx');
    for (const name of barrelExports(tsx, seen)) names.add(name);
  }
  return names;
}

/**
 * Rewrite an example so the site — and the reader — see what a consumer writes.
 *
 * An example is authored beside its component and imports it by a relative
 * path; every one of those paths is something the package publishes, so they
 * all collapse into the entry point a consumer would import that name from —
 * `@tecton/react` for a component, `@tecton/react/templates` for a template.
 * A name that no entry point publishes is a mistake worth failing the build
 * for: it would mean the code on the page is not code a reader can run.
 */
function rewriteSource(rawSource, {id, entryPoints}) {
  // A Windows checkout with autocrlf hands us CRLF; every pattern below is
  // written against LF, and the generated module should be LF regardless.
  const source = rawSource.replace(/\r\n/g, '\n');
  /** specifier → the names imported from it, in the order first seen. */
  const grouped = new Map(entryPoints.map(entry => [entry.specifier, []]));
  let imported = 0;
  let rest = source.replace(
    /^import\s+(type\s+)?\{([^}]*)\}\s+from\s+'(\.[^']*)';\n/gm,
    (line, typeOnly, names, from) => {
      for (const raw of names.split(',')) {
        const trimmed = raw.trim();
        if (!trimmed) continue; // trailing comma in a multi-line import
        const name = typeOnly ? `type ${trimmed}` : trimmed;
        // `Exported as Local` keeps the alias; the entry point must publish
        // the exported (left-hand) name.
        const bare = name.replace(/^type\s+/, '').replace(/\s+as\s+.*$/, '');
        const entry = entryPoints.find(candidate =>
          candidate.exports.has(bare),
        );
        if (!entry) {
          throw new Error(
            `${id} imports "${bare}" from "${from}", which no entry point of @tecton/react exports.`,
          );
        }
        const bucket = grouped.get(entry.specifier);
        if (!bucket.includes(name)) {
          bucket.push(name);
          imported += 1;
        }
      }
      return '';
    },
  );
  if (/from\s+'\.\.?\//.test(rest)) {
    throw new Error(`${id} still has a relative import after rewriting.`);
  }
  if (imported === 0) {
    throw new Error(`${id} imports nothing from the package.`);
  }
  const packageImports = [...grouped]
    .filter(([, names]) => names.length > 0)
    .map(
      ([specifier, names]) =>
        `import {${names.join(', ')}} from '${specifier}';\n`,
    )
    .join('');
  // Keep any remaining import (React's hooks) above the package imports.
  const otherImports = [...rest.matchAll(/^import .*;\n/gm)].map(
    match => match[0],
  );
  rest = rest.replace(/^import .*;\n/gm, '').replace(/^\n+/, '');
  return `${otherImports.join('')}${packageImports}\n${rest}`;
}

