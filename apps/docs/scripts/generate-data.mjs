#!/usr/bin/env node
/**
 * Builds the docs site out of the package it documents.
 *
 * Nothing on this site is written twice. Five kinds of source feed it:
 *
 *   - the **component docs** that ship inside `@astryxdesign/core`, the library
 *     `@tecton/react` re-exports one for one — 229 `.doc.mjs` files under
 *     `packages/react/node_modules/@astryxdesign/core/src`, plus `groups.doc.mjs`.
 *     Every string in them is rewritten to speak Tecton (see `speakTecton`);
 *   - the **examples**, ported 1:1 into `apps/docs/examples` and committed
 *     there: 646 blocks and 53 page templates, each with its own `.doc.mjs`;
 *   - the **guides** under `apps/docs/guides`;
 *   - the package's **built theme** and the design JSON it was transcribed
 *     from, which is what every foundations page prints;
 *   - the package's **changelog**.
 *
 * From those it writes two trees, both generated and both gitignored:
 *
 *   - `content/docs/**` — the MDX fumadocs compiles into pages, and the
 *     `meta.json` files that put them in the sidebar. Every route the site has
 *     comes from a file here.
 *   - `src/generated/**` — typed TypeScript the page components read: the
 *     registries, the grouped sidebar, the foundation data, and the loader maps
 *     of dynamic imports that mount an example in the reader's browser.
 *
 * The package has to be built first: the foundations pages read the token
 * modules out of `packages/react/dist/`.
 */
