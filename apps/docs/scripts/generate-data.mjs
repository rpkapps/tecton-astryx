/** `var(--name)` → `--name`. */
function tokenName(value) {
  const match = /^var\((--[^),]+)\)$/.exec(String(value));
  return match ? match[1] : String(value);
}

/** Flatten a nested token map into `{path, token}` rows, depth first. */
function flattenTokens(node, prefix = []) {
  const rows = [];
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('__')) continue;
    const trail = [...prefix, key];
    if (typeof value === 'string') {
      rows.push({path: trail.join('.'), token: tokenName(value)});
    } else if (value && typeof value === 'object') {
      rows.push(...flattenTokens(value, trail));
    }
  }
  return rows;
}

/**
 * What every custom property actually resolves to, read out of the built
 * stylesheets.
 *
 * The theme layer wins over the foundation layer at runtime, so the theme
 * sheet is read first and the component sheet only fills in what the theme
 * does not set (the spacing grid and the durations).
 */
function tokenValues() {
  const values = new Map();
  for (const sheet of ['tecton-tokens.css', 'tecton-components.css']) {
    const full = path.join(PACKAGE_DIST, sheet);
    if (!fs.existsSync(full)) {
      throw new Error(
        `packages/react/dist/${sheet} is missing. Build the package first.`,
      );
    }
    const css = fs.readFileSync(full, 'utf8');
    for (const match of css.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;}]+)[;}]/g)) {
      const [, name, raw] = match;
      if (values.has(name)) continue;
      values.set(name, raw.trim());
    }
  }
  return values;
}

/** Split `light-dark(a, b)` into the two values; anything else is both. */
function resolveValue(values, token) {
  const raw = values.get(token);
  if (!raw) return {};
  const pair = /^light-dark\(\s*(.+?)\s*,\s*(.+?)\s*\)$/.exec(raw);
  if (pair) return {value: raw, light: pair[1], dark: pair[2]};
  return {value: raw};
}

/** Flatten the semantic colour map into `{path, light, dark}` rows. */
function flattenPairs(node, prefix = []) {
  const rows = [];
  for (const [key, value] of Object.entries(node)) {
    const trail = [...prefix, key];
    if (Array.isArray(value)) {
      rows.push({path: trail.join('.'), light: value[0], dark: value[1]});
    } else if (value && typeof value === 'object') {
      rows.push(...flattenPairs(value, trail));
    }
  }
  return rows;
}

const normalise = value => value.toLowerCase().replace(/[^a-z0-9]/g, '');

/** Sentence case for a camelCase or dotted path segment. */
function label(segment) {
  const words = segment
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .toLowerCase()
    .trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

async function buildFoundations() {
  const {tecton, durationTokens} = await importDist('theme/tokens.js');
  const {tectonColor} = await importDist('theme/semantic.js');
  const {variants: typeVariants} = await importDist('theme/typography.js');
  const {tectonIconNames} = await importDist('icons/names.js');
  const colours = readJson('design/foundations/colors.json');
  const typography = readJson('design/foundations/typography.json');
  const spacing = readJson('design/foundations/spacing-and-radius.json');
  const values = tokenValues();

  /* Colour --------------------------------------------------------------- */

  // The design page's row descriptions, reachable from a token path.
  const described = new Map();
  for (const row of colours) {
    if (!row.description) continue;
    const description = row.description.trim();
    described.set(normalise(row.name), description);
    described.set(normalise(`${row.section} ${row.name}`), description);
  }
  const describe = pathValue => {
    const trail = pathValue.split('.');
    for (let start = 0; start < trail.length; start += 1) {
      const hit = described.get(normalise(trail.slice(start).join('')));
      if (hit) return hit;
    }
    return undefined;
  };

  const palettePairs = flattenPairs(tectonColor);
  let describedCount = 0;
  const paletteGroups = [];
  for (const row of palettePairs) {
    const [group] = row.path.split('.');
    const description = describe(row.path);
    if (description) describedCount += 1;
    let bucket = paletteGroups.find(entry => entry.name === group);
    if (!bucket) {
      bucket = {name: group, title: label(group), rows: []};
      paletteGroups.push(bucket);
    }
    bucket.rows.push({
      path: row.path.slice(group.length + 1),
      light: row.light,
      dark: row.dark,
      description,
    });
  }

  const colourTokens = flattenTokens(tecton.color).map(row => ({
    ...row,
    description: describe(row.path),
  }));

  /* Typography ----------------------------------------------------------- */

  const typeDescriptions = new Map(
    (typography.variants ?? []).map(entry => [
      entry.token,
      {
        description: (entry.description ?? '').trim(),
        section: entry.section,
        sample: entry.sample,
      },
    ]),
  );
  const typeRows = Object.entries(typeVariants).map(([name, variant]) => {
    const extra = typeDescriptions.get(name);
    return {
      name,
      size: variant.size,
      sizePx: `${Math.round(parseFloat(variant.size) * 16)}px`,
      weight: variant.weight,
      leading: Number(variant.leading).toFixed(2),
      isData: Boolean(variant.data),
      section: extra?.section ?? 'Interface',
      description: extra?.description,
      sample: extra?.sample ?? 'The quick brown fox',
    };
  });

  const fontFamilies = flattenTokens(tecton.font.family).map(row => ({
    ...row,
    ...resolveValue(values, row.token),
  }));

  /* Spacing, radius, shape, elevation, motion ---------------------------- */

  const spacingDescriptions = new Map(
    (spacing.tokens ?? []).map(entry => [
      normalise(entry.token),
      (entry.description ?? '').trim(),
    ]),
  );
  /** The design step whose value is the same number of pixels, if there is one. */
  const designStep = (group, value) => {
    const hit = (spacing.tokens ?? []).find(
      entry => entry.group === group && entry.value === value,
    );
    return hit
      ? {
          designToken: hit.token,
          description: spacingDescriptions.get(normalise(hit.token)),
        }
      : {};
  };

  const scaleRows = (map, group) =>
    flattenTokens(map).map(row => {
      const resolved = resolveValue(values, row.token);
      return {...row, ...resolved, ...designStep(group, resolved.value)};
    });

  const spacingRows = scaleRows(tecton.space, 'Spacing');
  const radiusRows = scaleRows(tecton.radius, 'Corner Radii');
  const sizeRows = flattenTokens(tecton.size).map(row => ({
    ...row,
    ...resolveValue(values, row.token),
  }));
  const borderRows = flattenTokens(tecton.border).map(row => ({
    ...row,
    ...resolveValue(values, row.token),
  }));
  const shadowRows = flattenTokens(tecton.shadow).map(row => ({
    ...row,
    ...resolveValue(values, row.token),
  }));
  const motionRows = Object.values(durationTokens)
    .filter(value => typeof value === 'string' && value.startsWith('var('))
    .map(value => {
      const token = tokenName(value);
      return {
        path: token.replace('--duration-', ''),
        token,
        ...resolveValue(values, token),
      };
    });

  return {
    paletteGroups,
    paletteDescribed: describedCount,
    paletteTotal: palettePairs.length,
    colourTokens,
    typeRows,
    fontFamilies,
    spacingRows,
    radiusRows,
    sizeRows,
    borderRows,
    shadowRows,
    motionRows,
    iconNames: [...tectonIconNames],
  };
}

