async function importDist(relative) {
  const full = path.join(PACKAGE_DIST, relative);
  if (!fs.existsSync(full)) {
    throw new Error(
      `${path.relative(REPO_ROOT, full)} is missing. Build the package first: pnpm --filter @tecton/react build`,
    );
  }
  return import(pathToFileURL(full).href);
}

function readJson(relative) {
  const full = path.join(REPO_ROOT, relative);
  if (!fs.existsSync(full)) {
    throw new Error(`${relative} is missing; a foundations page needs it.`);
  }
  return JSON.parse(fs.readFileSync(full, 'utf8'));
}

/** `var(--name)` → `--name`. */
function tokenName(value) {
  const match = /^var\((--[^),]+)\)$/.exec(String(value));
  return match ? match[1] : String(value);
}

/** Flatten a nested token map into `{path, token}` rows, depth first. */
function flattenTokens(node, prefix = []) {
  const rows = [];
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('__')) continue;
    const trail = [...prefix, key];
    if (typeof value === 'string') {
      rows.push({path: trail.join('.'), token: tokenName(value)});
    } else if (value && typeof value === 'object') {
      rows.push(...flattenTokens(value, trail));
    }
  }
  return rows;
}

function tokenValues() {
  const values = new Map();
  for (const sheet of ['tecton-tokens.css', 'tecton-components.css']) {
    const full = path.join(PACKAGE_DIST, sheet);
    if (!fs.existsSync(full)) {
      throw new Error(
        `packages/react/dist/${sheet} is missing. Build the package first.`,
      );
    }
    const css = fs.readFileSync(full, 'utf8');
    for (const match of css.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;}]+)[;}]/g)) {
      const [, name, raw] = match;
      if (values.has(name)) continue;
      values.set(name, raw.trim());
    }
  }
  return values;
}

/** Split `light-dark(a, b)` into the two values; anything else is both. */
function resolveValue(values, token) {
  const raw = values.get(token);
  if (!raw) return {};
  const pair = /^light-dark\(\s*(.+?)\s*,\s*(.+?)\s*\)$/.exec(raw);
  if (pair) return {value: raw, light: pair[1], dark: pair[2]};
  return {value: raw};
}

function flattenPairs(node, prefix = []) {
  const rows = [];
  for (const [key, value] of Object.entries(node)) {
    const trail = [...prefix, key];
    if (Array.isArray(value)) {
      rows.push({path: trail.join('.'), light: value[0], dark: value[1]});
    } else if (value && typeof value === 'object') {
      rows.push(...flattenPairs(value, trail));
    }
  }
  return rows;
}

const normalise = value => value.toLowerCase().replace(/[^a-z0-9]/g, '');

function label(segment) {
  const words = segment
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .toLowerCase()
    .trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

