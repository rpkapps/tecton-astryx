#!/usr/bin/env node
/**
 * Builds the docs site's data layer.
 *
 * Three kinds of documentation are authored as `*.doc.mjs`:
 *
 *   - a component doc beside each component (`Button/Button.doc.mjs`),
 *   - an example doc beside each example (`Button/examples/ButtonBasic.doc.mjs`),
 *   - a written topic under `content/docs/`.
 *
 * This script loads all three and writes typed, sorted TypeScript modules into
 * `src/generated/`, which is the only place the site reads documentation from.
 * Run it before `vite` — the `dev`, `build` and `typecheck` scripts already do.
 *
 * Examples are recorded with the path of their component file so a later phase
 * can render them live; this phase only needs to know they exist and which
 * component they belong to.
 */
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const APP_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const COMPONENT_SRC = path.resolve(APP_ROOT, '../../packages/react/src');
const TOPIC_SRC = path.join(APP_ROOT, 'content/docs');
const OUT_DIR = path.join(APP_ROOT, 'src/generated');

function findDocFiles(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === 'dist') continue;
      findDocFiles(full, out);
    } else if (entry.name.endsWith('.doc.mjs')) {
      out.push(full);
    }
  }
  return out;
}

async function load(files, decorate = () => ({})) {
  const loaded = [];
  for (const file of files.sort()) {
    const module = await import(pathToFileURL(file).href);
    const doc = module.docs ?? module.default;
    if (!doc?.name) {
      throw new Error(`${file} does not export a named \`docs\` object.`);
    }
    loaded.push({...doc, ...decorate(file, doc)});
  }
  return loaded.sort((a, b) => a.name.localeCompare(b.name));
}

function render({banner, typeName, constName, data}) {
  return `${banner}
import type {${typeName}} from '../types/docs';

export const ${constName}: readonly ${typeName}[] = ${JSON.stringify(data, null, 2)};
`;
}

const BANNER = `// Generated by scripts/generate-data.mjs. Do not edit by hand.
// Run \`pnpm --filter @tecton/docs generate\` to refresh.`;

const docFiles = findDocFiles(COMPONENT_SRC);
const isExample = file => file.split(path.sep).includes('examples');

const components = await load(docFiles.filter(file => !isExample(file)));
const examples = await load(docFiles.filter(isExample), file => ({
  path: path
    .relative(COMPONENT_SRC, file)
    .replaceAll(path.sep, '/')
    .replace(/\.doc\.mjs$/, '.tsx'),
}));
const topics = await load(findDocFiles(TOPIC_SRC));

// Every example a component lists has to exist, or the site links into nothing.
const byId = new Map(examples.map(example => [example.id, example]));
for (const component of components) {
  for (const id of component.examples ?? []) {
    if (!byId.has(id)) {
      throw new Error(
        `${component.name} lists the example "${id}", which has no doc file.`,
      );
    }
  }
}

await fsp.mkdir(OUT_DIR, {recursive: true});
await fsp.writeFile(
  path.join(OUT_DIR, 'componentRegistry.ts'),
  render({
    banner: BANNER,
    typeName: 'ComponentDoc',
    constName: 'componentRegistry',
    data: components,
  }),
  'utf8',
);
await fsp.writeFile(
  path.join(OUT_DIR, 'exampleRegistry.ts'),
  render({
    banner: BANNER,
    typeName: 'ExampleDoc',
    constName: 'exampleRegistry',
    data: examples,
  }),
  'utf8',
);
await fsp.writeFile(
  path.join(OUT_DIR, 'docsRegistry.ts'),
  render({
    banner: BANNER,
    typeName: 'DocTopic',
    constName: 'docsRegistry',
    data: topics,
  }),
  'utf8',
);

console.log(
  `Generated ${components.length} component docs, ${examples.length} examples and ${topics.length} topics into src/generated/.`,
);
