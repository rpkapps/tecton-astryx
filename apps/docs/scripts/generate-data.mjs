/** Which components a reader is likely to want next. */
function relatedTo(component) {
  if (component.related?.length) {
    return component.related.filter(name => componentNames.has(name));
  }
  const sameGroup = components
    .filter(
      other =>
        other.name !== component.name &&
        component.group &&
        other.group === component.group,
    )
    .map(other => other.name);
  const sameCategory = components
    .filter(
      other =>
        other.name !== component.name &&
        !sameGroup.includes(other.name) &&
        component.category &&
        other.category === component.category,
    )
    .map(other => other.name);
  return [...sameGroup, ...sameCategory].slice(0, 6);
}

