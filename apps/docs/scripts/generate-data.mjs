/** A lazy-loader map: what `<LivePreview>` reaches for when a page mounts. */
function loaderModule({name, dir, entries, comment}) {
  const lines = entries
    .map(id => `  ${JSON.stringify(id)}: () => import('./${dir}/${id}'),`)
    .join('\n');
  return `${BANNER}
${comment}
import type {ComponentType} from 'react';

export type ModuleLoader = () => Promise<Record<string, ComponentType>>;

export const ${name}: Readonly<Record<string, ModuleLoader>> = {
${lines}
};
`;
}

