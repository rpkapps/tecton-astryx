function findDocFiles(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === 'dist') continue;
      findDocFiles(full, out);
    } else if (entry.name.endsWith('.doc.mjs')) {
      out.push(full);
    }
  }
  return out;
}

/** `Button/Button.doc.mjs` → `Button`; the module a doc belongs to. */
function moduleOf(file) {
  return path
    .relative(UPSTREAM_SRC, path.dirname(file))
    .replaceAll(path.sep, '/');
}

/**
 * Humanise a raw group label into a spaced one — `TopNav` → `Top Nav`.
 * Upstream's `humanizeGroupLabel`, used when no member of the group is named
 * after it (the `Chat` group has no component literally called `Chat`).
 */
function humanizeGroupLabel(label) {
  if (/^\d+[A-Z]+$/.test(label)) return label;
  return label
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .trim();
}

const upstreamDocFiles = findDocFiles(UPSTREAM_SRC).sort();
if (upstreamDocFiles.length === 0) {
  throw new Error(
    `No component docs under ${path.relative(REPO_ROOT, UPSTREAM_SRC)}. Run pnpm install.`,
  );
}

/** Every doc file, loaded, rewritten, and tagged with the module it is in. */
const loadedDocs = [];
for (const file of upstreamDocFiles) {
  const module = await import(pathToFileURL(file).href);
  if (!module.docs) continue;
  const doc = rewriteDeep(plainData(module.docs));
  loadedDocs.push({
    file,
    module: moduleOf(file),
    stem: path.basename(file).replace(/\.doc\.mjs$/, ''),
    doc,
  });
}

const {GROUP_DOCS} = await import(
  pathToFileURL(path.join(UPSTREAM, 'groups.doc.mjs')).href
);
const groupDocs = rewriteDeep(plainData(GROUP_DOCS));

/** A doc that documents a subcomponent of another doc, not a module of its own. */
const isSubDoc = entry => Boolean(entry.doc.subComponentOf);

/** The primary doc of a module directory: the one the module is named after. */
const primaryOf = new Map();
for (const entry of loadedDocs) {
  if (isSubDoc(entry)) continue;
  const isNamedAfterModule =
    entry.stem === entry.module ||
    entry.doc.name === entry.module.split('/').pop();
  if (isNamedAfterModule && !primaryOf.has(entry.module)) {
    primaryOf.set(entry.module, entry.doc.name ?? entry.stem);
  }
}

/** The entry point a consumer imports a module from. */
function importPathFor(entry) {
  if (entry.doc.importPath) return entry.doc.importPath;
  return `@tecton/react/${entry.module}`;
}

/**
 * One page per main doc.
 *
 * A doc with `subComponentOf` documents part of another component: its props
 * are printed on that component's page rather than getting a route of their
 * own, which is what keeps the sidebar a list of things a consumer imports.
 */
const pages = [];
const subDocsByParent = new Map();
for (const entry of loadedDocs) {
  if (!isSubDoc(entry)) continue;
  const parent = entry.doc.subComponentOf;
  subDocsByParent.set(parent, [...(subDocsByParent.get(parent) ?? []), entry]);
}

for (const entry of loadedDocs) {
  if (isSubDoc(entry)) continue;
  const {doc} = entry;
  const name = doc.name ?? entry.stem;
  const isHook = Array.isArray(doc.params) || name.startsWith('use');
  const inlineSubs = (doc.components ?? [])
    .filter(sub => sub.name && sub.name !== name)
    // A name-only entry is a cross-reference to a sibling `.doc.mjs`; its props
    // are read from that file instead (the `subDocsByParent` branch below).
    .filter(sub => Object.keys(sub).length > 1)
    .map(sub => ({
      name: sub.name,
      displayName: sub.displayName ?? sub.name,
      description: sub.description ?? '',
      props: Array.isArray(sub.props) ? sub.props : [],
      isHook: sub.name.startsWith('use'),
    }));
  const fileSubs = (subDocsByParent.get(name) ?? []).map(sub => ({
    name: sub.doc.name ?? sub.stem,
    displayName: sub.doc.displayName ?? sub.doc.name ?? sub.stem,
    description: sub.doc.description ?? sub.doc.usage?.description ?? '',
    props: Array.isArray(sub.doc.props) ? sub.doc.props : [],
    params: Array.isArray(sub.doc.params) ? sub.doc.params : null,
    returns: Array.isArray(sub.doc.returns) ? sub.doc.returns : null,
    isHook:
      (sub.doc.name ?? sub.stem).startsWith('use') ||
      Array.isArray(sub.doc.params),
  }));
  const subcomponents = [...fileSubs, ...inlineSubs]
    .filter(
      (sub, index, all) => all.findIndex(o => o.name === sub.name) === index,
    )
    .sort((a, b) => a.name.localeCompare(b.name));

  pages.push({
    name,
    displayName: doc.displayName ?? name,
    module: entry.module,
    moduleName: name,
    importPath: importPathFor(entry),
    group: doc.group ?? null,
    category: doc.category ?? null,
    keywords: doc.keywords ?? [],
    description: doc.usage?.description ?? doc.description ?? '',
    summary: doc.description ?? doc.usage?.description ?? '',
    usage: doc.usage ?? null,
    props: Array.isArray(doc.props) ? doc.props : [],
    playground: doc.playground ?? null,
    theming: doc.theming ?? null,
    params: Array.isArray(doc.params) ? doc.params : null,
    returns: Array.isArray(doc.returns) ? doc.returns : null,
    relatedComponents: doc.relatedComponents ?? null,
    relatedHooks: doc.relatedHooks ?? null,
    isHook,
    isHiddenFromOverview: doc.isHiddenFromOverview === true,
    parentDoc: isHook
      ? (primaryOf.get(entry.module) ?? null)
      : (doc.components?.length ?? 0) > 0
        ? name
        : null,
    subcomponents,
    examples: [],
    showcase: null,
  });
}

pages.sort((a, b) => a.name.localeCompare(b.name));

const pageByName = new Map();
for (const page of pages) {
  if (pageByName.has(page.name)) {
    throw new Error(
      `Two upstream docs are both called "${page.name}"; a page name has to be unique.`,
    );
  }
  pageByName.set(page.name, page);
}

/**
 * Which page documents a given component name.
 *
 * A block's `exampleFor` may name a subcomponent (`ChatMessageBubble`) or a
 * hook (`useTableSelection`) rather than a module; either way the example
 * belongs on the page that documents it.
 */
const pageOfComponent = new Map();
for (const page of pages) {
  pageOfComponent.set(page.name, page.name);
}
for (const page of pages) {
  for (const sub of page.subcomponents) {
    if (!pageOfComponent.has(sub.name))
      pageOfComponent.set(sub.name, page.name);
  }
}
for (const entry of loadedDocs) {
  if (!isSubDoc(entry)) continue;
  const name = entry.doc.name ?? entry.stem;
  if (pageOfComponent.has(name)) continue;
  const parent = pageOfComponent.get(entry.doc.subComponentOf);
  if (parent) pageOfComponent.set(name, parent);
}
for (const entry of loadedDocs) {
  const owner = entry.doc.name ?? entry.stem;
  const target = pageOfComponent.get(owner);
  if (!target) continue;
  for (const hidden of entry.doc.hiddenComponents ?? []) {
    const name = typeof hidden === 'string' ? hidden : hidden.name;
    if (name && !pageOfComponent.has(name)) pageOfComponent.set(name, target);
  }
}

