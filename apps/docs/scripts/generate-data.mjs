/**
 * Upstream's `generateGroupedComponentRegistry`, over one entry per page.
 *
 * A doc's `group` makes a group; a group with one member flattens back to a
 * plain entry; the group's label is its canonical member's display name, or a
 * humanised form of the raw label when no member is named after it. Hooks that
 * live in `hooks/` and anything in the `Utilities` group go to Utilities, which
 * the sidebar keeps collapsed; a hook whose parent doc has subcomponents joins
 * its parent's group instead.
 */
function buildGroupedSidebar(entries) {
  const utilities = [];
  const groups = new Map();
  const ungrouped = [];

  const parentDocsWithComponents = new Set(
    entries
      .filter(
        entry =>
          entry.parentDoc && !entry.isHook && entry.subcomponents.length > 0,
      )
      .map(entry => entry.parentDoc),
  );

  for (const entry of entries) {
    const item = {
      name: entry.name,
      displayName: entry.displayName,
      href: `/docs/components/${entry.name}`,
      description: entry.summary,
    };
    if (
      entry.group === 'Utilities' ||
      (entry.isHook && entry.module === 'hooks')
    ) {
      utilities.push(item);
      continue;
    }
    if (entry.group) {
      groups.set(entry.group, [...(groups.get(entry.group) ?? []), item]);
      continue;
    }
    if (entry.isHook && !entry.parentDoc) {
      groups.set(entry.module, [...(groups.get(entry.module) ?? []), item]);
      continue;
    }
    if (
      entry.isHook &&
      entry.parentDoc &&
      parentDocsWithComponents.has(entry.parentDoc)
    ) {
      groups.set(entry.parentDoc, [
        ...(groups.get(entry.parentDoc) ?? []),
        item,
      ]);
      continue;
    }
    if (entry.isHook) {
      utilities.push(item);
      continue;
    }
    ungrouped.push(item);
  }

  const items = [];
  for (const [label, members] of groups) {
    members.sort((a, b) => a.name.localeCompare(b.name));
    if (members.length === 1) {
      items.push({
        sortKey: members[0].name,
        item: {type: 'entry', ...members[0]},
      });
      continue;
    }
    const canonicalName = groupDocs[label]?.canonical;
    const canonical =
      members.find(member => member.name === label) ??
      members.find(member => member.name === canonicalName);
    items.push({
      sortKey: label,
      item: {
        type: 'group',
        label,
        displayName: canonical?.displayName ?? humanizeGroupLabel(label),
        description:
          groupDocs[label]?.description ?? canonical?.description ?? '',
        entries: members.map(({name, displayName, href}) => ({
          name,
          displayName,
          href,
        })),
      },
    });
  }
  for (const item of ungrouped)
    items.push({sortKey: item.name, item: {type: 'entry', ...item}});
  items.sort((a, b) => a.sortKey.localeCompare(b.sortKey));

  return {
    items: items.map(entry => entry.item),
    utilities: utilities.sort((a, b) => a.name.localeCompare(b.name)),
  };
}

const sidebar = buildGroupedSidebar(pages);

