/** Load a ported doc object: every one of them exports `doc`. */
async function loadPortedDoc(file) {
  const module = await import(pathToFileURL(file).href);
  const doc = module.doc ?? module.docs;
  if (!doc) throw new Error(`${file} does not export a \`doc\` object.`);
  return doc;
}

