/**
 * Make authored prose safe to drop into MDX.
 *
 * Doc text is Markdown — inline code in backticks and `[label](/path)` links —
 * but MDX also reads `{` as an expression and `<` as a tag. Neither ever means
 * that here, so both are escaped everywhere except inside a code span.
 */
function mdxText(text) {
  return String(text)
    .split(/(`[^`]*`)/g)
    .map((part, index) =>
      index % 2 === 1 ? part : part.replace(/([{<])/g, '\\$1'),
    )
    .join('')
    .replace(
      /\]\(\/(components|foundations|templates|changelog)\b/g,
      '](/docs/$1',
    );
}

/** A fenced code block whose fence is always longer than anything inside it. */
function fence(code, language = '') {
  const longest = Math.max(
    2,
    ...[...String(code).matchAll(/`+/g)].map(match => match[0].length),
  );
  const ticks = '`'.repeat(longest + 1);
  return `${ticks}${language}\n${String(code).replace(/\n$/, '')}\n${ticks}`;
}

/** Frontmatter is plain text, not Markdown. */
function plain(text) {
  return String(text).replace(/`/g, '').replace(/\s+/g, ' ').trim();
}

function frontmatter(fields) {
  const lines = Object.entries(fields)
    .filter(([, value]) => value !== undefined && value !== '')
    .map(([key, value]) => `${key}: ${JSON.stringify(plain(value))}`);
  return `---\n${lines.join('\n')}\n---`;
}

/** A JSX attribute list from a plain object; strings become expressions. */
function attrs(props) {
  return Object.entries(props)
    .filter(([, value]) => value !== undefined && value !== null)
    .map(([key, value]) => `${key}={${JSON.stringify(value)}}`)
    .join(' ');
}

function guideBlock(block) {
  switch (block.type) {
    case 'prose':
      return mdxText(block.text);
    case 'code':
      return [
        block.caption
          ? `<CodeCaption>${mdxText(block.caption)}</CodeCaption>`
          : undefined,
        fence(block.code, block.language ?? 'text'),
      ]
        .filter(Boolean)
        .join('\n\n');
    case 'list':
      return block.items
        .map((item, index) =>
          block.ordered
            ? `${index + 1}. ${mdxText(item)}`
            : `- ${mdxText(item)}`,
        )
        .join('\n');
    case 'table': {
      const head = `| ${block.columns.map(mdxText).join(' | ')} |`;
      const rule = `| ${block.columns.map(() => '---').join(' | ')} |`;
      const body = block.rows
        .map(row => `| ${row.map(cell => mdxText(cell)).join(' | ')} |`)
        .join('\n');
      return [
        block.caption
          ? `<CodeCaption>${mdxText(block.caption)}</CodeCaption>`
          : undefined,
        [head, rule, body].join('\n'),
      ]
        .filter(Boolean)
        .join('\n\n');
    }
    default:
      throw new Error(`Unknown block type "${block.type}".`);
  }
}

function guideMdx(topic) {
  const body = topic.sections
    .map(section =>
      [`## ${mdxText(section.title)}`, ...section.content.map(guideBlock)].join(
        '\n\n',
      ),
    )
    .join('\n\n');
  return `${frontmatter({
    title: topic.title,
    description: topic.description,
  })}\n\n${MDX_BANNER}\n\n${body}\n`;
}

